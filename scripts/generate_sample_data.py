"""Script: Reproducible Synthetic Dataset Generator.

Generates configurable database export datasets across varying entropy levels,
repetition ratios, schema variations, and record lengths.
"""

import csv
import gzip
import io
import os
from pathlib import Path
import random
from typing import Iterator, List, Optional, Tuple

DEPARTMENTS = ["Engineering", "Finance", "Sales", "HumanResources", "Operations", "Legal", "Marketing", "Support"]
STATUSES = ["ACTIVE", "PENDING", "COMPLETED", "SUSPENDED", "ARCHIVED"]
CATEGORIES = ["Enterprise", "MidMarket", "SMB", "Government", "Internal"]


def generate_record(
    record_id: int,
    repetitive: bool = False,
    long_text: bool = False,
    null_ratio: float = 0.05,
    rng: Optional[random.Random] = None,
) -> List[str]:
    """Generate a single tabular record."""
    r = rng or random

    if repetitive:
        cust_code = f"CUST-00{record_id % 5}"
        dept = "Operations"
        cat = "Enterprise"
        status = "ACTIVE"
        val = "100.00"
        desc = "Standard recurring automated billing entry processed successfully"
        ts = "2026-01-01 00:00:00"
        opt = ""
    else:
        cust_code = f"CUST-{r.randint(100000, 999999)}"
        dept = r.choice(DEPARTMENTS)
        cat = r.choice(CATEGORIES)
        status = r.choice(STATUSES)
        val = f"{r.uniform(10.0, 9999.0):.2f}"
        if long_text:
            desc = f"Audit log transaction #{record_id} generated by worker node {r.randint(1, 99)} at latency {r.randint(10, 500)}ms payload {r.randbytes(16).hex()}"
        else:
            desc = f"Transaction record {record_id} customer {cust_code} status {status}"
        ts = f"2026-{r.randint(1, 12):02d}-{r.randint(1, 28):02d} {r.randint(0, 23):02d}:{r.randint(0, 59):02d}:{r.randint(0, 59):02d}"
        opt = "" if r.random() < null_ratio else f"OPT-{r.randint(1, 500)}"

    return [str(record_id), cust_code, dept, cat, desc, val, ts, status, opt]


def generate_csv_stream(
    row_count: int,
    repetitive: bool = False,
    long_text: bool = False,
    seed: int = 42,
    include_header: bool = True,
    schema_variant: int = 0,
) -> Iterator[str]:
    """Yield CSV lines incrementally with deterministic random seed."""
    rng = random.Random(seed)

    if schema_variant == 1:
        # Extra column
        header = ["id", "customer_code", "department", "category", "description", "numeric_value", "timestamp", "status", "optional_value", "extra_notes"]
    elif schema_variant == 2:
        # Dropped column
        header = ["id", "customer_code", "department", "category", "description", "numeric_value", "timestamp", "status"]
    else:
        header = ["id", "customer_code", "department", "category", "description", "numeric_value", "timestamp", "status", "optional_value"]

    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")

    if include_header:
        writer.writerow(header)
        yield out.getvalue()
        out.seek(0)
        out.truncate(0)

    for i in range(1, row_count + 1):
        rec = generate_record(i, repetitive=repetitive, long_text=long_text, rng=rng)
        if schema_variant == 1:
            rec.append("AutoGeneratedNotice")
        elif schema_variant == 2:
            rec = rec[:-1]
        writer.writerow(rec)

        if i % 1000 == 0:
            yield out.getvalue()
            out.seek(0)
            out.truncate(0)

    rem = out.getvalue()
    if rem:
        yield rem


def write_compressed_csv(
    destination_path: Path,
    row_count: int,
    repetitive: bool = False,
    long_text: bool = False,
    seed: int = 42,
    compression_level: int = 6,
    schema_variant: int = 0,
) -> int:
    """Stream synthetic CSV directly into a gzip file without unbounded memory buffering.

    Returns:
        Exact compressed file size in bytes.
    """
    destination_path.parent.mkdir(parents=True, exist_ok=True)
    with open(destination_path, "wb") as raw_f:
        with gzip.GzipFile(fileobj=raw_f, mode="wb", compresslevel=compression_level) as gz_f:
            for text_chunk in generate_csv_stream(row_count, repetitive=repetitive, long_text=long_text, seed=seed, schema_variant=schema_variant):
                gz_f.write(text_chunk.encode("utf-8"))

    return destination_path.stat().st_size

